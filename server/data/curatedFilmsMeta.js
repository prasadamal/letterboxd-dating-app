export function collectionsFromSections(sectionText) {
  const tags = new Set()
  if (/GLOBAL CANON/.test(sectionText)) tags.add('canon')
  if (/INTERNATIONAL \/ WORLD/.test(sectionText)) tags.add('world')
  if (/INDIAN CINEMA/.test(sectionText)) tags.add('indian')
  if (/MALAYALAM/.test(sectionText)) tags.add('malayalam').add('indian')
  if (/CROWD-PLEASERS/.test(sectionText)) tags.add('crowd')
  if (/UNDERSEEN/.test(sectionText)) tags.add('underseen')
  if (/DIVISIVE/.test(sectionText)) tags.add('divisive')
  if (/OVERRATED/.test(sectionText)) tags.add('debated')
  return [...tags]
}
